package com.app.cimacloud.Utils

import android.app.Application
import android.app.Instrumentation
import android.content.Context
import android.content.ContextWrapper
import android.os.Build
import android.os.Process
import android.util.Log
import com.animeday.FakeContext
import java.io.File
import java.io.InputStream
import java.lang.reflect.Modifier
import java.util.zip.ZipFile

/**
 * Uses the JNI ABI verified for the bundled CimaCloud libnative-lib.so.
 * Native methods are registered dynamically by JNI_OnLoad, so this wrapper's
 * class name and method names/signatures must match the library's registration.
 *
 * Important: createPackageContext() and an AnimeDay Application object do not change the
 * process UID or Binder caller identity. Calling the installed app's native method from this
 * plugin process is not guaranteed to produce a token equivalent to one generated by AnimeDay
 * running in its own process.
 */
object NativeLib {
    private const val LIB_NAME = "libnative-lib.so"
    private const val TOKEN_PROP = "animeday.native.token"
    private const val OFFICIAL_PACKAGE = "com.anime.day"
    private const val OFFICIAL_NATIVE_CLASS = "com.anime.day.Utils.NativeLib"
    private const val LOG_TAG = "AnimeDayNative"

    @Volatile
    private var loaded = false

    private val lock = Any()

    external fun buildSecure(context: Context): String?

    external fun decryptResponse(data: String, key: String): String?

    /**
     * Extracts libnative-lib.so from this plugin package and loads it.
     * buildSecure() reads package metadata, so [attestationContext] prefers the real installed
     * AnimeDay context and otherwise supplies the compatibility identity through [FakeContext].
     */
    fun load(context: Context) {
        if (loaded) return
        synchronized(lock) {
            if (loaded) return
            val so = findOrExtract(context)
            System.load(so.absolutePath)
            // The native library shares global OpenSSL/BoringSSL state and is NOT
            // thread-safe. Perform the first (one-time initialisation) call while
            // still holding the lock so concurrent callers never race the init.
            runCatching { buildSecure(attestationContext(context)) }
            loaded = true
        }
    }

    fun secureId(context: Context): String? {
        // Prefer the installed app's own class and native library, but this call still executes
        // under the plugin's process identity. A non-empty return value is not proof that the
        // server will accept it as an official-process attestation.
        // Serialize calls because both native implementations may hold process-global state.
        synchronized(lock) {
            val official = runCatching { buildSecureFromInstalledApp(context) }
                .onFailure { error ->
                    Log.i(
                        LOG_TAG,
                        "official AnimeDay native call unavailable; falling back to bundled JNI error=${error.javaClass.simpleName}",
                    )
                }
                .getOrNull()
            if (!official.isNullOrEmpty() && official.length > 8) {
                System.setProperty(TOKEN_PROP, official)
                Log.i(LOG_TAG, "secure token generated by installed AnimeDay native library")
                return official
            }
            Log.w(LOG_TAG, "official AnimeDay native call returned no usable token; falling back to bundled JNI")
        }

        // If the official app is absent or its JNI entrypoint cannot be called, retain the
        // standalone compatibility path. This also supports users without AnimeDay installed.
        load(context)
        synchronized(lock) {
            val fresh = runCatching {
                buildSecure(attestationContext(context))
            }.getOrNull()
            if (!fresh.isNullOrEmpty() && fresh.length > 8) {
                // Process-global cache survives CloudStream plugin (re)loads, which
                // create a new ClassLoader where the .so cannot be re-opened.
                System.setProperty(TOKEN_PROP, fresh)
                return fresh
            }
            // Native unavailable (e.g. after a plugin reload) -> fall back to cache.
            return System.getProperty(TOKEN_PROP)?.takeIf { it.isNotEmpty() }
        }
    }

    private fun buildSecureFromInstalledApp(context: Context): String? {
        val hostContext = context.applicationContext ?: context
        val flags = Context.CONTEXT_INCLUDE_CODE or Context.CONTEXT_IGNORE_SECURITY
        val officialContext = hostContext.createPackageContext(OFFICIAL_PACKAGE, flags)
        logNativeProcessIdentity(officialContext)
        val classLoader = officialContext.classLoader
            ?: throw ClassNotFoundException("AnimeDay package class loader unavailable")
        val nativeClass = Class.forName(OFFICIAL_NATIVE_CLASS, true, classLoader)
        val method = try {
            nativeClass.getDeclaredMethod("buildSecure", Context::class.java)
        } catch (_: NoSuchMethodException) {
            nativeClass.getMethod("buildSecure", Context::class.java)
        }.apply { isAccessible = true }
        val receiver = if (Modifier.isStatic(method.modifiers)) {
            null
        } else {
            val instance = try {
                nativeClass.getDeclaredField("INSTANCE").apply { isAccessible = true }.get(null)
            } catch (_: Throwable) {
                nativeClass.getDeclaredConstructor().apply { isAccessible = true }.newInstance()
            }
            instance
        }
        // The official APK calls this native method with its MyApplication instance. A plain
        // createPackageContext() may return CloudStream from getApplicationContext(), while the
        // old FakeContext also substituted PackageManager methods (including UID/signature
        // lookups) despite returning real PackageInfo objects for the common calls. Attach the
        // APK's declared Application to a narrow identity wrapper instead: all package metadata,
        // resources, services, and PackageManager calls still come from Android's real package
        // context. Do not call onCreate(); it has unrelated app/session side effects.
        val packageContext = OfficialPackageContext(officialContext)
        val applicationClass = officialContext.applicationInfo.className
            ?.takeIf { it.isNotBlank() }
            ?: Application::class.java.name
        val application = Instrumentation().newApplication(classLoader, applicationClass, packageContext)
        Log.i(LOG_TAG, "calling installed AnimeDay native attestation with official Application/context; JNI still runs in the caller process")
        return method.invoke(receiver, application) as? String
    }

    /**
     * Records only non-secret process-boundary facts. A package Context changes package-scoped
     * APIs, but it cannot change Process.myUid() or the Binder caller identity used by native code.
     * Never log UID values, package lists, or the generated attestation token.
     */
    private fun logNativeProcessIdentity(packageContext: Context) {
        val processUid = Process.myUid()
        val packageUid = runCatching { packageContext.applicationInfo.uid }.getOrDefault(-1)
        val processUidPackageCount = runCatching {
            packageContext.packageManager.getPackagesForUid(processUid)?.size ?: -1
        }.getOrDefault(-1)
        Log.i(
            LOG_TAG,
            "native process identity samePackageUid=${processUid == packageUid} " +
                "processUidPackageCount=$processUidPackageCount " +
                "processUidShared=${processUidPackageCount >= 2}",
        )
    }

    /** Keeps Context.getApplicationContext() inside the installed package without faking PackageManager data. */
    private class OfficialPackageContext(base: Context) : ContextWrapper(base) {
        override fun getPackageName(): String = OFFICIAL_PACKAGE

        override fun getOpPackageName(): String = OFFICIAL_PACKAGE

        override fun getApplicationContext(): Context = this
    }

    fun decrypt(context: Context, data: String, key: String): String? {
        load(context)
        synchronized(lock) {
            return runCatching { decryptResponse(data, key) }.getOrNull()
        }
    }

    /**
     * ANDROID_ID is scoped to the calling app identity on modern Android releases. Read it from
     * AnimeDay's installed package context when available, rather than CloudStream's host context.
     */
    fun deviceIdentityContext(context: Context): Context {
        val appContext = context.applicationContext ?: context
        return try {
            val officialContext = appContext.createPackageContext(OFFICIAL_PACKAGE, 0)
            Log.i(LOG_TAG, "using installed AnimeDay context for device identifier")
            officialContext.applicationContext ?: officialContext
        } catch (error: Throwable) {
            Log.i(
                LOG_TAG,
                "AnimeDay context unavailable for device identifier; using host context error=${error.javaClass.simpleName}",
            )
            appContext
        }
    }

    /**
     * Use the real app context and package metadata when AnimeDay is installed. Some devices
     * expose the app through createPackageContext even when the host app cannot query it directly;
     * FakeContext/FakePackageManager then supplies the compatibility identity and legacy fallback.
     */
    private fun attestationContext(context: Context): Context {
        val appContext = context.applicationContext ?: context
        return try {
            val officialContext = appContext.createPackageContext(OFFICIAL_PACKAGE, 0)
            Log.i(LOG_TAG, "installed package context available for native attestation")
            FakeContext(officialContext)
        } catch (error: Throwable) {
            Log.i(
                LOG_TAG,
                "installed package context unavailable; using compatibility context error=${error.javaClass.simpleName}",
            )
            FakeContext(appContext)
        }
    }

    private fun findOrExtract(context: Context): File {
        val abis = LinkedHashSet<String>()
        abis.addAll(Build.SUPPORTED_ABIS)
        if (Build.CPU_ABI.isNotEmpty()) abis.add(Build.CPU_ABI)

        // A unique directory per load attempt is required: Android's linker keys
        // loaded libraries by real path + ClassLoader namespace, so re-opening the
        // same path from a new (reloaded) plugin ClassLoader fails with
        // "already opened by ClassLoader ... can't open in ClassLoader ...".
        val tag = java.lang.Long.toString(System.nanoTime(), 36)
        val base = File(context.filesDir, "animeday_native")
        val dir = File(base, tag).apply { mkdirs() }

        for (abi in abis) {
            val entry = "lib/$abi/$LIB_NAME"
            val input = openResource(entry) ?: openFromPluginFile(entry) ?: continue
            val out = File(dir, "libnative-lib-$abi.so")
            input.use { ins -> out.outputStream().use { ins.copyTo(it) } }
            out.setReadable(true, false)
            out.setExecutable(true, false)
            out.setWritable(true)
            if (out.length() > 0L) {
                // Drop copies left behind by previous (re)loads.
                base.listFiles()?.forEach { if (it != dir) runCatching { it.deleteRecursively() } }
                return out
            }
        }
        throw UnsatisfiedLinkError("$LIB_NAME not found inside plugin for ABIs=$abis")
    }

    private fun openResource(entry: String): InputStream? = try {
        NativeLib::class.java.classLoader?.getResourceAsStream(entry)
    } catch (_: Throwable) {
        null
    }

    private fun openFromPluginFile(entry: String): InputStream? {
        val path = pluginFilePath() ?: return null
        return try {
            ZipFile(path).use { zip ->
                val z = zip.getEntry(entry) ?: return null
                zip.getInputStream(z).use { it.readBytes() }.inputStream()
            }
        } catch (_: Throwable) {
            null
        }
    }

    private fun pluginFilePath(): String? {
        try {
            val loc = NativeLib::class.java.protectionDomain?.codeSource?.location
            if (loc != null) {
                val f = File(loc.toURI())
                if (f.exists()) return f.absolutePath
            }
        } catch (_: Throwable) {
        }
        try {
            val cl = NativeLib::class.java.classLoader ?: return null
            val pathListField = cl.javaClass.getDeclaredField("pathList").apply { isAccessible = true }
            val pathList = pathListField.get(cl) ?: return null
            val dexField = pathList.javaClass.getDeclaredField("dexElements").apply { isAccessible = true }
            val elements = dexField.get(pathList) as? Array<*> ?: return null
            for (el in elements) {
                if (el == null) continue
                val pathField = el.javaClass.getDeclaredField("path").apply { isAccessible = true }
                when (val p = pathField.get(el)) {
                    is File -> if (p.exists()) return p.absolutePath
                    is String -> if (File(p).exists()) return p
                }
            }
        } catch (_: Throwable) {
        }
        return null
    }
}
